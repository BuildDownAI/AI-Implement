async function runSelectedInternalReviewers(params: {
  context: PipelineContext;
  reporter: StepReporter;
  reviewers: SelectedReviewer[];
  retryPolicy: ReturnType<typeof normalizeRetryPolicy>;
  prNumber: string;
  iteration: number;
  diff: string;
  previousFindings: string;
  model: string;
  sleep: (ms: number) => Promise<void>;
}): Promise<SelectedReviewerResult> {
  const findings: PostPushReviewLedgerFinding[] = [];
  const feedbackParts: string[] = [];
  let approved = true;
  let lastTelemetry: RunTelemetry | undefined;
  let costUsd: number | null = null;

  for (const { selection, definition, legacy } of params.reviewers) {
    const reviewerId = selection.id;
    const reportId = legacy ? `post-push-review.${params.iteration}` : `post-push-review.${params.iteration}.${reviewerId}`;
    const stage = legacy ? `post-push-review/review-${params.iteration}` : `post-push-review/${reviewerId}-review-${params.iteration}`;
    const reportInputs = legacy
      ? { iteration: params.iteration, prNumber: params.prNumber }
      : { iteration: params.iteration, prNumber: params.prNumber, reviewerId };
    const maxTurns = definition.maxTurns ?? params.retryPolicy.reviewMaxTurns;
    const prompt = definition.buildPrompt({
      issueIdentifier: params.context.data.issueIdentifier,
      issueTitle: params.context.data.issueTitle,
      issueDescription: params.context.data.issueDescription,
      prNumber: params.prNumber,
      diff: params.diff,
      previousFindings: params.previousFindings,
    });

    let reviewResult = await params.context.llmExecutor.invoke({
      prompt,
      model: definition.model ?? params.model,
      maxTurns,
      tools: READ_ONLY_ALLOWED_TOOLS,
      jsonSchema: definition.outputSchema,
      stage,
      expectsStructuredOutput: true,
    });
    let reviewStageAttempt = 1;
    let reviewStageClassified: FailureRecord | undefined;
    while (reviewResult.telemetry?.outcome !== "max_turns" && reviewFailureMessage(reviewResult) !== null) {
      reviewStageClassified = classifyLlmResult(reviewResult, {
        stage,
        attempt: reviewResult.attempts ?? 1,
        expectsStructuredOutput: true,
        elapsedMs: reviewResult.telemetry?.durationMs ?? undefined,
      });
      if (reviewStageClassified.category !== "transient" || reviewStageAttempt > params.retryPolicy.stageRetries) break;
      await params.reporter.report({
        id: `${reportId}.retry${reviewStageAttempt}`,
        type: "custom",
        status: "failed",
        started_at: new Date().toISOString(),
        ended_at: new Date().toISOString(),
        parent_step_id: "post-push-review",
        inputs: reportInputs,
        outputs: { failure: reviewStageClassified, telemetry: reviewResult.telemetry },
        logs_url: null,
      });
      costUsd = addExtraCost(costUsd, reviewResult.telemetry?.costUsd);
      await params.sleep(computeBackoffMs(reviewStageAttempt, params.retryPolicy));
      reviewStageAttempt++;
      reviewResult = await params.context.llmExecutor.invoke({
        prompt,
        model: definition.model ?? params.model,
        maxTurns,
        tools: READ_ONLY_ALLOWED_TOOLS,
        jsonSchema: definition.outputSchema,
        stage,
        expectsStructuredOutput: true,
      });
      reviewStageClassified = undefined;
    }
    costUsd = addExtraCost(costUsd, reviewResult.telemetry?.costUsd);
    lastTelemetry = reviewResult.telemetry;

    if (reviewStageClassified && reviewStageClassified.category === "transient") {
      const failure = { ...reviewStageClassified, stage: "post-push-review", code: "PROVIDER_UNAVAILABLE" as const, retryable: false };
      const telemetryPart = reviewResult.telemetry ? summaryLine(reviewResult.telemetry) : "no telemetry reported";
      const feedback = compactErrorMessage(`Reviewer ${reviewerId} could not run because the model provider was unavailable after ${reviewStageAttempt} attempt(s) (${telemetryPart}).`);
      await params.reporter.report({
        id: reportId,
        type: "custom",
        status: "failed",
        started_at: new Date().toISOString(),
        ended_at: new Date().toISOString(),
        parent_step_id: "post-push-review",
        inputs: reportInputs,
        outputs: { approved: false, feedback, issues: [], blockingIssues: [], failure, telemetry: reviewResult.telemetry },
        logs_url: null,
      });
      return { stopped: true, terminationReason: "provider_unavailable", feedback, failure, costUsd, priorLlmFailure: true };
    }

    if (reviewResult.telemetry?.outcome === "max_turns") {
      const failure = {
        ...classifyLlmResult(reviewResult, { stage, attempt: reviewResult.attempts ?? 1, expectsStructuredOutput: true, elapsedMs: reviewResult.telemetry?.durationMs ?? undefined }),
        category: "invalid_output" as const,
        code: "REVIEWER_TURNS_EXHAUSTED" as const,
        retryable: false,
        reviewMaxTurns: maxTurns,
      };
      const feedback = `${reviewerId} ran out of turns at the configured cap (${maxTurns}). ${summaryLine(reviewResult.telemetry)}`;
      await params.reporter.report({
        id: reportId,
        type: "custom",
        status: "failed",
        started_at: new Date().toISOString(),
        ended_at: new Date().toISOString(),
        parent_step_id: "post-push-review",
        inputs: reportInputs,
        outputs: { approved: false, feedback, issues: [], blockingIssues: [], failure, telemetry: reviewResult.telemetry },
        logs_url: null,
      });
      return { stopped: true, terminationReason: "reviewer_turns_exhausted", feedback, failure, costUsd };
    }

    const reviewFailure = reviewFailureMessage(reviewResult);
    if (reviewFailure) {
      const failure = classifyLlmResult(reviewResult, { stage, attempt: reviewResult.attempts ?? 1, expectsStructuredOutput: true, elapsedMs: reviewResult.telemetry?.durationMs ?? undefined });
      const telemetryPart = reviewResult.telemetry ? summaryLine(reviewResult.telemetry) : "no telemetry reported";
      const feedback = compactErrorMessage(`Reviewer ${reviewerId} failed: ${reviewFailure} (${telemetryPart}; ${failure.category}/${failure.code})`);
      await params.reporter.report({
        id: reportId,
        type: "custom",
        status: "failed",
        started_at: new Date().toISOString(),
        ended_at: new Date().toISOString(),
        parent_step_id: "post-push-review",
        inputs: reportInputs,
        outputs: { ...failedReviewOutputs(feedback), telemetry: reviewResult.telemetry },
        logs_url: null,
      });
      return { stopped: true, terminationReason: "review_failed", feedback, costUsd, priorLlmFailure: true };
    }

    if (reviewResult.structuredOutput === undefined) {
      const feedback = compactErrorMessage(legacy
        ? `Reviewer returned no structured_output: ${reviewResult.stdout || "(empty stdout)"}`
        : `Reviewer ${reviewerId} returned no structured_output: ${reviewResult.stdout || "(empty stdout)"}`);
      await params.reporter.report({ id: reportId, type: "custom", status: "failed", started_at: new Date().toISOString(), ended_at: new Date().toISOString(), parent_step_id: "post-push-review", inputs: reportInputs, outputs: { ...failedReviewOutputs(feedback), telemetry: reviewResult.telemetry }, logs_url: null });
      return { stopped: true, terminationReason: "invalid_review", feedback, costUsd };
    }

    let verdict: ReviewerVerdict;
    let reviewerFeedback = "";
    try {
      if (legacy) {
        const legacyVerdict = parseReviewVerdict(reviewResult.structuredOutput);
        reviewerFeedback = legacyVerdict.feedback;
        const legacyFindings = legacyVerdict.blockingIssues.map((issue) => {
          const reviewIssue = issueFromVerdictIssue(issue);
          return {
            source: "ai-implement-internal" as const,
            reviewerId,
            severity: "blocking" as const,
            body: postPushIssueText(reviewIssue),
            issue: reviewIssue,
          };
        });
        verdict = {
          approved: legacyVerdict.approved,
          findings: legacyFindings.map((finding) => ({ severity: finding.severity, body: finding.body })),
        };
        findings.push(...legacyFindings);
      } else {
        verdict = parseReviewerDefinitionVerdict(reviewResult.structuredOutput);
      }
    } catch (err) {
      const reason = err instanceof Error ? err.message : String(err);
      const feedback = compactErrorMessage(legacy
        ? `Reviewer returned invalid structured review output: ${reason}.`
        : `Reviewer ${reviewerId} returned invalid structured review output: ${reason}.`);
      await params.reporter.report({ id: reportId, type: "custom", status: "failed", started_at: new Date().toISOString(), ended_at: new Date().toISOString(), parent_step_id: "post-push-review", inputs: reportInputs, outputs: { ...failedReviewOutputs(feedback), telemetry: reviewResult.telemetry }, logs_url: null });
      return { stopped: true, terminationReason: "invalid_review", feedback, costUsd };
    }

    if (!legacy && verdict.findings.length === 0 && verdict.approved === false) {
      const feedback = `Reviewer ${reviewerId} returned approved=false without findings[].`;
      await params.reporter.report({ id: reportId, type: "custom", status: "failed", started_at: new Date().toISOString(), ended_at: new Date().toISOString(), parent_step_id: "post-push-review", inputs: reportInputs, outputs: { ...failedReviewOutputs(feedback), telemetry: reviewResult.telemetry }, logs_url: null });
      return { stopped: true, terminationReason: "invalid_review", feedback, costUsd };
    }

    const reviewerFindings = legacy ? [] : verdict.findings.map((finding) => reviewerFindingToLedgerFinding(reviewerId, finding));
    findings.push(...reviewerFindings);
    if (selection.gates) {
      approved = approved && verdict.approved && (legacy ? verdict.findings.length === 0 : reviewerFindings.length === 0);
    }
    feedbackParts.push(legacy && reviewerFeedback ? reviewerFeedback : `${reviewerId}: ${reviewerFindings.length === 0 ? "approved" : `${reviewerFindings.length} finding(s)`}`);
    if (!legacy) {
      await params.reporter.report({
        id: reportId,
        type: "custom",
        status: "passed",
        started_at: new Date().toISOString(),
        ended_at: new Date().toISOString(),
        parent_step_id: "post-push-review",
        inputs: reportInputs,
        outputs: { approved: verdict.approved, findings: reviewerFindings, telemetry: reviewResult.telemetry },
        logs_url: null,
      });
    }
  }

  return { approved, feedback: feedbackParts.join("\n"), findings, telemetry: lastTelemetry, costUsd };
}

async function reportInvalidStructuredReview(
  reporter: StepReporter,
  ghSpawn: (args: string[]) => SpawnResult,
  prNumber: string,
  iteration: number,
  feedback: string,
  telemetry?: RunTelemetry,
) {
  await reporter.report({
    id: `post-push-review.${iteration}`,
    type: "custom",
    status: "failed",
    started_at: new Date().toISOString(),
    ended_at: new Date().toISOString(),
    parent_step_id: "post-push-review",
    inputs: { iteration, prNumber },
    outputs: { ...failedReviewOutputs(feedback), ...(telemetry ? { telemetry } : {}) },
    logs_url: null,
  });
  const marker = `<!-- ai-implement post-push iter=${iteration} review-invalid -->`;
  postPrComment(
    ghSpawn,
    prNumber,
    `${marker}\n⚠️ Post-push review returned invalid output.\n\n${feedback}\n\nThe implementation PR is still available, but this automated review pass did not finish. No actionable code feedback was produced by this review attempt.\n\n**Merge readiness:** Manual review required; automated review did not complete.`,
    marker,
  );
}

export const postPushReviewStep: StepModule<PostPushReviewInputs, PostPushReviewOutputs> = {
  async run(context, inputs, reporter) {
    const ghSpawn = inputs.ghSpawn ?? makeDefaultGhSpawn(inputs.workspaceDir);
    const gitSpawn = inputs.gitSpawn ?? makeDefaultGitSpawn(inputs.workspaceDir);
    const maxIterations = inputs.maxIterations ?? DEFAULT_MAX_ITERATIONS;
    const model = inputs.model ?? context.data.model ?? "claude-sonnet-5";
    const prNumber = String(inputs.prNumber ?? "");
    if (!prNumber) throw new Error("post-push-review requires a PR number");
    const retryPolicy = normalizeRetryPolicy(context.data.retryPolicy);

    const sleep = inputs.sleep ?? ((ms: number) => new Promise<void>((resolve) => setTimeout(resolve, ms)));
    const reviewWaitPollMs = inputs.reviewWaitPollMs ?? DEFAULT_REVIEW_WAIT_POLL_MS;
    const reviewWaitTimeoutMs = inputs.reviewWaitTimeoutMs ?? DEFAULT_REVIEW_WAIT_TIMEOUT_MS;

    const startMarker = "<!-- ai-implement post-push status=start -->";

    let iteration = 0;
    let approved = false;
    let feedback = "";
    let forcePushed = 0;
    let terminationReason: PostPushReviewTerminationReason = "iterations_exhausted";
    let reviewerFailure: FailureRecord | undefined;
    const reviewHistory: ReviewFinding[] = [];
    // Every review invocation (including superseded retry attempts) and every fix-pass
    // invocation this step runs, summed — mirrors report-card.ts's extraCostUsd so the
    // ticket-facing total (run-autonomous.ts) can agree with the report card (BAC-27201).
    let costUsd: number | null = null;
    // Set to true when a real LLM failure (non-zero exit) occurs. A benign terminal
    // (PrMergedError or OperatorCancelledError) thrown afterward while posting the failure
    // comment is suppressed so the genuine failure conclusion surfaces rather than being masked.
    let priorLlmFailure = false;

    try {
    assertPrWritable(ghSpawn, prNumber);
    postPrComment(
      ghSpawn,
      prNumber,
      `${startMarker}\n🔍 Running post-implementation review...`,
      startMarker,
    );

    const configuredReviewerSelection = inputs.reviewers;
    const selectedReviewerResolution = configuredReviewerSelection !== undefined
      ? await resolveSelectedInternalReviewers(configuredReviewerSelection, inputs.trustedReviewerDefinitions)
      : null;
    if (configuredReviewerSelection?.length === 0) {
      return reportReviewerSelectionFailure(
        reporter,
        ghSpawn,
        prNumber,
        selectionFailureMessage("empty-selection"),
      );
    }
    if (selectedReviewerResolution && selectedReviewerResolution.unresolvedIds.length > 0) {
      const message = selectionFailureMessage("unresolved", selectedReviewerResolution.unresolvedIds);
      console.warn(`[post-push-review] ${message}`);
      return reportReviewerSelectionFailure(reporter, ghSpawn, prNumber, message);
    }
    if (selectedReviewerResolution && selectedReviewerResolution.reviewers.length === 0) {
      const message = selectionFailureMessage("empty-internal");
      console.warn(`[post-push-review] ${message}`);
      return reportReviewerSelectionFailure(reporter, ghSpawn, prNumber, message);
    }
    const selectedInternalReviewers = selectedReviewerResolution?.reviewers ?? null;

    while (iteration < maxIterations && !approved) {
      iteration++;
      // Probe before the LLM call: a merge/close between iterations exits immediately rather than burning a full reviewer turn.
      assertPrWritable(ghSpawn, prNumber);

      const diffRes = ghSpawn(["pr", "diff", prNumber]);
      if (diffRes.exitCode !== 0) throw new Error(`gh pr diff failed: ${resultMessage(diffRes)}`);

      const previousFindings = formatReviewHistory(reviewHistory);
      const legacyReviewPrompt = `You are reviewing the diff for PR #${prNumber} against issue ${context.data.issueIdentifier}: ${context.data.issueTitle}.

Set approved=true only when no code changes are needed. If you find any bug,
missing requirement, unsafe behavior, test gap, or follow-up that should be
fixed in this PR, set approved=false and put every actionable item in
blocking_issues[].
The orchestrator treats blocking_issues[] as the only internal blocking finding
list; it will not infer blockers from feedback prose. If something must be
fixed before merge, it must be present in blocking_issues[].
Do not set approved=false for future/later-task concerns that are not required
by this issue; mention those in feedback only.

This is a complete merge-readiness review, not an incremental comment pass.
Inspect the whole diff before deciding. Do not stop after the first issue.
Before producing JSON, check requirements coverage, changed API/data contracts,
error handling, security, regressions, edge cases, and test coverage.

Every blocking_issues[] entry must be self-contained and immediately
actionable. Use structured objects with title, location, problem, and
required_fix fields. Include the affected file/function when possible, the
failing behavior, and the required fix. Do not abbreviate or truncate issue
details; do not use ellipses. Do not put praise, overall status, or
optional/future cleanup in blocking_issues[]. Do not write feedback that
refers to issues "above" unless those issues are explicitly listed in
blocking_issues[].

Use feedback for a short overall review summary that adds context not already
present in blocking_issues[]. Do not repeat the blocking_issues[] text
verbatim in feedback.

On follow-up reviews, first verify every previous issue is fixed, then review
the entire updated diff again for newly introduced or newly visible blockers.
If a previous issue remains unresolved, keep it in blocking_issues[] with the
current reason it is still blocking.

Issue description:
${context.data.issueDescription}

Previous post-push review findings:
${previousFindings}

${DIFF_INJECTION_PREAMBLE}

<pr_diff>
${diffRes.stdout}
</pr_diff>

Output ONLY valid JSON: {"approved": bool, "blocking_issues": [{"title": "string", "location": "file/function; omit when unknown", "problem": "full failing behavior", "required_fix": "full required fix"}], "score": int, "progress_delta": int, "feedback": "string"}.`;

      const activeInternalReviewers: SelectedReviewer[] = selectedInternalReviewers ?? [{
        selection: { id: "legacy-post-push-review", gates: true },
        definition: {
          id: "legacy-post-push-review",
          buildPrompt: () => legacyReviewPrompt,
          outputSchema: REVIEW_VERDICT_JSON_SCHEMA,
        },
        legacy: true,
      }];
      const selectedReviewerResult = await runSelectedInternalReviewers({
        context,
        reporter,
        reviewers: activeInternalReviewers,
        retryPolicy,
        prNumber,
        iteration,
        diff: diffRes.stdout,
        previousFindings,
        model,
        sleep,
      });
      costUsd = addExtraCost(costUsd, selectedReviewerResult.costUsd);
      if (isSelectedReviewerStop(selectedReviewerResult)) {
        terminationReason = selectedReviewerResult.terminationReason;
        feedback = selectedReviewerResult.feedback;
        if (selectedReviewerResult.failure) reviewerFailure = selectedReviewerResult.failure;
        if (selectedReviewerResult.priorLlmFailure) priorLlmFailure = true;

        const lastFinding = reviewHistory.length > 0 ? reviewHistory[reviewHistory.length - 1] : null;
        const carriedContextBlock = lastFinding
          ? capPreservingLines(
              blockingIssuesBlock(lastFinding.issues, { heading: "Blocking issues from the previous review:" }),
              CARRIED_BLOCKERS_MAX_CHARS,
            )
          : "";
        const forcePushedLine = forcePushed > 0
          ? `\n\n${forcePushed} automated fix revision(s) were pushed and not re-reviewed.`
          : "";
        const notReviewedPhrase = iteration >= 2 ? "the latest revision was not reviewed" : "the code was not reviewed";

        if (terminationReason === "reviewer_turns_exhausted") {
          feedback = `${feedback}${forcePushedLine}${carriedContextBlock}`;
          const marker = `<!-- ai-implement post-push iter=${iteration} reviewer-turns-exhausted -->`;
          postPrComment(
            ghSpawn,
            prNumber,
            `${marker}\n🟠 The post-push reviewer ran out of turns at the configured cap (${reviewerFailure?.reviewMaxTurns ?? "unknown"}); ${notReviewedPhrase}.${forcePushedLine}${carriedContextBlock}\n\n**Merge readiness:** Manual review required; the reviewer did not finish.`,
            marker,
          );
        } else if (terminationReason === "provider_unavailable") {
          feedback = `${feedback}${forcePushedLine}${carriedContextBlock}`;
          const marker = `<!-- ai-implement post-push iter=${iteration} provider-unavailable -->`;
          postPrComment(
            ghSpawn,
            prNumber,
            `${marker}\n🟠 The model provider was unavailable during review; ${notReviewedPhrase}.\n\n${feedback}\n\nThe implementation PR is still available. This is usually transient — re-dispatch once the provider recovers.\n\n**Merge readiness:** Manual review required; automated review did not complete.`,
            marker,
          );
        } else if (terminationReason === "invalid_review") {
          const marker = `<!-- ai-implement post-push iter=${iteration} review-invalid -->`;
          postPrComment(
            ghSpawn,
            prNumber,
            `${marker}\n⚠️ Post-push review returned invalid output.\n\n${feedback}\n\nThe implementation PR is still available, but this automated review pass did not finish. No actionable code feedback was produced by this review attempt.\n\n**Merge readiness:** Manual review required; automated review did not complete.`,
            marker,
          );
        } else {
          const marker = `<!-- ai-implement post-push iter=${iteration} review-failed -->`;
          postPrComment(
            ghSpawn,
            prNumber,
            `${marker}\n⚠️ Post-push review could not complete.\n\n${feedback}\n\nThe implementation PR is still available, but this automated review pass did not finish. No actionable code feedback was produced by this review attempt.\n\n**Merge readiness:** Manual review required; automated review did not complete.`,
            marker,
          );
        }
        break;
      }

      const selectedInternalFindings = selectedReviewerResult.findings;
      const verdict = {
        approved: selectedReviewerResult.approved,
        blockingIssues: [] as VerdictReviewIssue[],
        feedback: selectedReviewerResult.feedback,
      };
      const reviewResult = {
        stdout: "",
        exitCode: 0,
        tokensUsed: 0,
        telemetry: selectedInternalReviewers ? undefined : selectedReviewerResult.telemetry,
      } as LLMResult;

      // The external review (e.g. Claude Code Review) runs concurrently and finishes
      // around the same time as the internal LLM review above. Wait for its check run
      // on the PR's current head SHA to reach a terminal state, then read its findings,
      // so merge readiness is decided against the real external verdict rather than the
      // empty snapshot that exists when both reviews start.
      const externalReviewResult = shouldCollectExternalReviewFindings(inputs.reviewProviders)
        ? await waitForExternalReviewCompletion(ghSpawn, prNumber, {
            sleep,
            pollMs: reviewWaitPollMs,
            timeoutMs: reviewWaitTimeoutMs,
            configuredCheckNames: inputs.reviewCheckNames,
          })
        : { state: "skipped" as ExternalReviewState, headSha: "" };
      const externalReviewState = externalReviewResult.state;
      const externalReviewPending = externalReviewState === "running";
      const externalFindingsResult = externalReviewState === "skipped"
        ? { findings: [] as ReviewLedgerFinding[], findingsUnavailable: false }
        : collectExternalReviewFindingsFromGh(ghSpawn, prNumber);
      const externalFindings = externalFindingsResult.findings;
      const findingsUnavailable = externalFindingsResult.findingsUnavailable;

      // CI gate: collect failing non-review checks so a red build can never produce
      // "Ready to merge". Uses the head SHA already resolved by waitForExternalReviewCompletion.
      const failingCiChecks = (externalReviewState !== "skipped" && externalReviewResult.headSha)
        ? findFailingCiChecks(ghSpawn, externalReviewResult.headSha, inputs.reviewCheckNames)
        : [];

      const internalIssues = verdict.blockingIssues.map(issueFromVerdictIssue);
      for (const checkName of failingCiChecks) {
        internalIssues.push({
          title: "CI check failing",
          problem: `CI check '${checkName}' is failing on the current head`,
          requiredFix: `Fix the underlying defect causing '${checkName}' to fail`,
        });
      }

      const reviewLedger = buildReviewLedger(internalIssues, [...selectedInternalFindings, ...externalFindings], inputs.reviewers);
      const gatingReviewFindings = reviewLedger.filter((finding) => isReviewLedgerFindingGating(finding, inputs.reviewers));
      const advisoryReviewFindings = reviewLedger.filter((finding) => !isReviewLedgerFindingGating(finding, inputs.reviewers));
      const gatingExternalFindings = gatingReviewFindings.filter((finding) => finding.source !== "ai-implement-internal");
      const advisoryExternalFindings = advisoryReviewFindings;
      let issues = internalIssuesFromReviewLedger(gatingReviewFindings);
      const externalReviewVerdictBlocks = externalFindingsResult.verdictSource === "review-contract"
        && (externalFindingsResult.verdict === "changes_requested" || externalFindingsResult.verdict === "incomplete");
      console.log(
        `[post-push-review] Review ledger findings: gating=${gatingReviewFindings.length} advisory=${advisoryReviewFindings.length}`,
      );

      feedback = suppressDuplicateExternalFeedback(verdict.feedback, externalFindings);
      if (issues.length === 0 && verdict.approved === false && gatingExternalFindings.length === 0 && !findingsUnavailable && !externalReviewVerdictBlocks) {
        terminationReason = "invalid_review";
        feedback = "Reviewer returned invalid structured review output: approved=false requires at least one blocking_issues[] entry.";
        await reportInvalidStructuredReview(reporter, ghSpawn, prNumber, iteration, feedback, reviewResult.telemetry);
        break;
      }

      // A close that lands while the reviewer call is in flight must not become an approved or

      // fix-pass exit — the approved exit on a last iteration never pushes, so nothing else would catch it.

      // Fail closed: the internal verdict is clean and no blockers are visible, but the
      // external review check did not finish within the wait budget. Do not auto-approve
      // against a reviewer that is still in flight — defer to a human.
      const cleanInternalNoGatingFindings = verdict.approved === true && issues.length === 0 && gatingExternalFindings.length === 0;
      const internalApprovable = cleanInternalNoGatingFindings && !findingsUnavailable && !externalReviewVerdictBlocks;
      if (cleanInternalNoGatingFindings && externalReviewPending) {
        terminationReason = "external_review_pending";
        feedback = "External review did not complete within the wait budget; not auto-approving.";
        await reporter.report({
          id: `post-push-review.${iteration}`,
          type: "custom",
          status: "passed",
          started_at: new Date().toISOString(),
          ended_at: new Date().toISOString(),
          parent_step_id: "post-push-review",
          inputs: { iteration, prNumber },
          outputs: { approved: false, feedback, issues: [], blockingIssues: [], telemetry: reviewResult.telemetry },
          logs_url: null,
        });
        const marker = `<!-- ai-implement post-push iter=${iteration} external-pending -->`;
        postPrComment(
          ghSpawn,
          prNumber,
          `${marker}\n⚠️ Internal review passed, but the external review did not complete within the wait budget. Not auto-approving.\n\n**Merge readiness:** Manual review required; external review did not complete.`,
          marker,
        );
        break;
      }

      if (cleanInternalNoGatingFindings && (findingsUnavailable || externalReviewVerdictBlocks)) {
        terminationReason = "invalid_review";
        feedback = externalReviewVerdictBlocks
          ? "External review returned a structured verdict that blocks merge without machine-readable findings; not auto-approving."
          : "External review findings could not be parsed; not auto-approving.";
        await reporter.report({
          id: `post-push-review.${iteration}`,
          type: "custom",
          status: "passed",
          started_at: new Date().toISOString(),
          ended_at: new Date().toISOString(),
          parent_step_id: "post-push-review",
          inputs: { iteration, prNumber },
          outputs: { approved: false, feedback, issues: [], blockingIssues: [], telemetry: reviewResult.telemetry },
          logs_url: null,
        });
        const marker = `<!-- ai-implement post-push iter=${iteration} invalid-external-review -->`;
        postPrComment(
          ghSpawn,
          prNumber,
          `${marker}\n⚠️ Internal review passed, but the external review verdict was unavailable or incomplete. Not auto-approving.${reviewFindingsCommentBlock(advisoryExternalFindings, { advisory: true })}${findingsUnavailableBlock(findingsUnavailable)}\n\n**Merge readiness:** Manual review required; external review verdict unavailable.`,
          marker,
        );
        break;
      }

      approved = approved || (internalApprovable && !externalReviewPending);
      reviewHistory.push({ iteration, issues: [...issues], feedback });

      await reporter.report({
        id: `post-push-review.${iteration}`,
        type: "custom",
        status: "passed",
        started_at: new Date().toISOString(),
        ended_at: new Date().toISOString(),
        parent_step_id: "post-push-review",
        inputs: { iteration, prNumber },
        outputs: { approved, feedback, issues: issues.map(postPushIssueText), blockingIssues: issues, telemetry: reviewResult.telemetry },
        logs_url: null,
      });

      if (approved) {
        terminationReason = "approved";
        const marker = `<!-- ai-implement post-push iter=${iteration} -->`;
        submitPrReview(ghSpawn, prNumber, `${AI_IMPLEMENT_NATIVE_REVIEW_MARKER}\nAI-Implement post-push review approved this PR.`);
        postPrComment(
          ghSpawn,
          prNumber,
          `${marker}\n✅ Approved (${iteration} iteration${iteration > 1 ? "s" : ""}).\n\n${feedback}${reviewFindingsCommentBlock(advisoryExternalFindings, { advisory: true })}${findingsUnavailableBlock(findingsUnavailable)}\n\n**Merge readiness:** Ready to merge.`,
          marker,
        );
        break;
      }

      if (iteration >= maxIterations) {
        terminationReason = "iterations_exhausted";
        const marker = `<!-- ai-implement post-push iter=${iteration} -->`;
        submitPrReview(
          ghSpawn,
          prNumber,
          `${AI_IMPLEMENT_NATIVE_REVIEW_MARKER}\nAI-Implement post-push review found unresolved blockers.\n\n${formatIssueList(issues)}${reviewFindingsCommentBlock(gatingExternalFindings)}${reviewFindingsCommentBlock(advisoryExternalFindings, { advisory: true })}`,
        );
        postPrComment(
          ghSpawn,
          prNumber,
          `${marker}\n⚠️ Reached review cap (${maxIterations} iterations) without approval.${blockingIssuesBlock(issues)}${reviewFindingsCommentBlock(gatingExternalFindings)}${reviewFindingsCommentBlock(advisoryExternalFindings, { advisory: true })}${findingsUnavailableBlock(findingsUnavailable)}${reviewerSummaryBlock(feedback, issues)}\n\n**Merge readiness:** Not ready to merge.`,
          marker,
        );
        break;
      }

      const feedbackMarker = `<!-- ai-implement post-push iter=${iteration} -->`;
      postPrComment(
        ghSpawn,
        prNumber,
        `${feedbackMarker}\n⚠️ Reviewer found issues — starting fix pass ${fixPassLabel(iteration, maxIterations)}...${blockingIssuesBlock(issues)}${reviewFindingsCommentBlock(gatingExternalFindings)}${reviewFindingsCommentBlock(advisoryExternalFindings, { advisory: true })}${findingsUnavailableBlock(findingsUnavailable)}${reviewerSummaryBlock(feedback, issues)}\n\n**Merge readiness:** Not ready to merge.`,
        feedbackMarker,
      );

      const issueList = issues.length > 0
        ? formatIssueListForPrompt(issues)
        : "None provided.";

      const fixPrompt = `You are fixing reviewer feedback on PR #${prNumber} for issue ${context.data.issueIdentifier}: ${context.data.issueTitle}.

Do NOT create a new branch or PR. Make changes to the current working tree. After your changes, the harness will commit and push.

Fix every listed issue, not only the easiest or first issue. Treat the list as
a required repair plan. Before editing, inspect the relevant code paths so the
fix is consistent with local architecture and tests. After editing, review the
full resulting diff yourself against the issue requirements and the complete
review history; fix any directly related defect, regression, or missing test
you discover during that self-review.

Do not make broad unrelated refactors. If an issue is invalid or impossible to
fix safely, make the smallest defensible code change you can and leave the
working tree otherwise clean; the next review will decide merge readiness.

When you finish, include a final JSON object in stdout with this shape:
{"fixed":["short description of each concrete fix"],"testing":["checks run or not run"],"notes":"anything important for reviewers"}
Keep each fixed[] item specific and user-facing; it will be posted to the PR.

${FEEDBACK_INJECTION_PREAMBLE}

<reviewer_feedback>
Review history:
${formatReviewHistory(reviewHistory)}

Issues:
${issueList}

Summary:
${feedback}
${requiredReviewFindingsBlock(gatingExternalFindings)}
</reviewer_feedback>`;

      const fixResult = await context.llmExecutor.invoke({
        prompt: fixPrompt,
        model,
        maxTurns: FIX_MAX_TURNS,
        stage: `post-push-review/fix-${iteration}`,
        expectsStructuredOutput: false,
      });
      costUsd = addExtraCost(costUsd, fixResult.telemetry?.costUsd);
      if (fixResult.exitCode !== 0) {
        priorLlmFailure = true;
        terminationReason = "fix_failed";
        const failure = compactErrorMessage(`Fix-pass LLM failed (${llmResultMessage(fixResult)})`);
        // The fix pass reports as its own custom sub-step (BAC-27201) — same `post-push-review.`
        // step_id prefix the review sub-step uses, so report-card.ts's cost query picks up its
        // spend even on a failed pass.
        await reporter.report({
          id: `post-push-review.fix-${iteration}`,
          type: "custom",
          status: "failed",
          started_at: new Date().toISOString(),
          ended_at: new Date().toISOString(),
          parent_step_id: "post-push-review",
          inputs: { iteration, prNumber },
          outputs: { error: failure, telemetry: fixResult.telemetry },
          logs_url: null,
        });
        const marker = `<!-- ai-implement post-push iter=${iteration} fix-failed -->`;
        postPrComment(
          ghSpawn,
          prNumber,
          `${marker}\n⚠️ Fix pass ${fixPassLabel(iteration, maxIterations)} could not complete.\n\n${failure}\n\nNo automated fix was pushed in this pass.\n\n**Merge readiness:** Not ready to merge.`,
          marker,
        );
        feedback = failure;
        break;
      }

      await reporter.report({
        id: `post-push-review.fix-${iteration}`,
        type: "custom",
        status: "passed",
        started_at: new Date().toISOString(),
        ended_at: new Date().toISOString(),
        parent_step_id: "post-push-review",
        inputs: { iteration, prNumber },
        outputs: { telemetry: fixResult.telemetry },
        logs_url: null,
      });

      const add = gitSpawn(["add", "-A"]);
      if (add.exitCode !== 0) throw new Error(`git add failed: ${resultMessage(add)}`);

      const status = gitSpawn(["status", "--porcelain"]);
      if (status.exitCode !== 0) throw new Error(`git status failed: ${resultMessage(status)}`);
      if (!status.stdout.trim()) {
        terminationReason = "no_changes";
        const marker = `<!-- ai-implement post-push iter=${iteration} no-changes -->`;
        submitPrReview(
          ghSpawn,
          prNumber,
          `${AI_IMPLEMENT_NATIVE_REVIEW_MARKER}\nAI-Implement fix pass made no changes; blockers remain.${blockingIssuesBlock(issues, { heading: "Unresolved blocking issues:" })}${reviewFindingsCommentBlock(gatingExternalFindings)}${reviewFindingsCommentBlock(advisoryExternalFindings, { advisory: true })}`,
        );
        postPrComment(
          ghSpawn,
          prNumber,
          `${marker}\n⚠️ Fix pass ${fixPassLabel(iteration, maxIterations)} completed with no file changes; stopping the post-push review loop.${blockingIssuesBlock(issues, { heading: "Unresolved blocking issues:" })}${reviewFindingsCommentBlock(gatingExternalFindings)}${reviewFindingsCommentBlock(advisoryExternalFindings, { advisory: true })}${reviewerSummaryBlock(feedback, issues)}\n\n**Merge readiness:** Not ready to merge.`,
          marker,
        );
        break;
      }

      const commit = gitSpawn(["commit", "-m", `fix: address review feedback (iter ${iteration})`]);
      if (commit.exitCode !== 0) throw new Error(`git commit failed: ${resultMessage(commit)}`);

      const revParse = gitSpawn(["rev-parse", "--short", "HEAD"]);
      const commitLabel = revParse.exitCode === 0 && revParse.stdout.trim()
        ? ` Commit: \`${revParse.stdout.trim()}\`.`
        : "";
      const fixSummary = parseFixSummary(fixResult.stdout);
      const fixSummaryBlock = formatFixSummaryBlock(fixSummary);
      const changesSummary = summarizeHeadChanges(gitSpawn);
      const changesBlock = changesSummary ? `\n\nChanges pushed:\n${changesSummary}` : "";

      const branchName = currentBranchName(gitSpawn);
      const remoteRef = `refs/heads/${branchName}`;
      // A fix pass can run long enough to outlive the token minted by pushStep.
      // Re-vend at the actual write boundary; transient vending failures retain
      // the latest token already present in the environment and origin URL.
      assertPrWritable(ghSpawn, prNumber);
      await refreshCredentialsBeforePush(context, inputs);
      const expectedRemoteSha = remoteBranchSha(gitSpawn, branchName);
      const push = gitSpawn([
        "push",
        "origin",
        `HEAD:${remoteRef}`,
        `--force-with-lease=${remoteRef}:${expectedRemoteSha ?? ""}`,
      ]);
      if (push.exitCode !== 0) throw new Error(`git push --force-with-lease rejected: ${resultMessage(push)}`);

      forcePushed++;
      const marker = `<!-- ai-implement post-push iter=${iteration} fix-complete -->`;
      postPrComment(
        ghSpawn,
        prNumber,
        `${marker}\n✅ Fix pass ${fixPassLabel(iteration, maxIterations)} completed and pushed changes.${commitLabel}${fixSummaryBlock}${changesBlock}\n\n**Merge readiness:** Awaiting follow-up review.`,
        marker,
      );
    }
    } catch (err) {
      if (err instanceof OperatorCancelledError) {
        if (priorLlmFailure) {
          // A real LLM failure already set terminationReason — return that conclusion
          // so the genuine failure surfaces rather than being masked by the operator cancel.
          console.warn(
            `[post-push-review] PR #${prNumber} was closed by operator while posting failure comment — ` +
              `genuine failure surfaces as ${terminationReason}`,
          );
          return { approved, iterations: iteration, finalFeedback: feedback, forcePushedRevisions: forcePushed, terminationReason, costUsd, ...(reviewerFailure ? { failure: reviewerFailure } : {}) };
        }
        // No prior genuine failure — the operator cancel is the sole anomaly.
        terminationReason = "operator_cancelled";
        console.warn(`[post-push-review] PR #${prNumber} was closed by operator — surfacing as OPERATOR_CANCELLED`);
        throw err;
      }
      if (err instanceof PrMergedError) {
        if (priorLlmFailure) {
          // A real LLM failure already set terminationReason — surface the genuine failure
          // rather than masking it with the benign merge event.
          console.warn(
            `[post-push-review] PR #${prNumber} was merged while posting failure comment — ` +
              `genuine failure surfaces as ${terminationReason}`,
          );
          return { approved, iterations: iteration, finalFeedback: feedback, forcePushedRevisions: forcePushed, terminationReason, costUsd, ...(reviewerFailure ? { failure: reviewerFailure } : {}) };
        }
        terminationReason = "pr_merged";
        console.warn(`[post-push-review] PR #${prNumber} was merged under the run — exiting as pr_merged`);
        return { approved: true, iterations: iteration, finalFeedback: "", forcePushedRevisions: forcePushed, terminationReason: "pr_merged", costUsd };
      }
      throw err;
    }

    return {
      approved,
      iterations: iteration,
      finalFeedback: feedback,
      forcePushedRevisions: forcePushed,
      terminationReason,
      costUsd,
      ...(reviewerFailure ? { failure: reviewerFailure } : {}),
    };
  },
};

export default postPushReviewStep;
